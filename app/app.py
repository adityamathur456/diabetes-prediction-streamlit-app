# Load Model & Scaler

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
model_path = os.path.join(BASE_DIR, "model/artifacts", "diabetes.pkl")
# model_path = r"C:\Users\adity\OneDrive\Documents\Internship\diabetes-prediction-streamlit-app\model\artifacts\diabetes.pkl"
# scaler_path = r"C:\Users\adity\OneDrive\Documents\Internship\diabetes-prediction-streamlit-app\model\artifacts\scaler.pkl"
scaler_path = os.path.join(BASE_DIR, "model/artifacts", "scaler.pkl")

classifier = joblib.load(model_path)
scaler = joblib.load(scaler_path)

# App Header
st.title("🩺 Diabetes Prediction System")
st.caption("AI-powered medical risk assessment with interactive analytics")

# Input Section (Two Column Layout)
col1, col2 = st.columns(2)

with col1:
    patient_name = st.text_input("Patient Name")
    glucose = st.number_input("Glucose Level", 0)
    blood_pressure = st.number_input("Blood Pressure", 0)
    skin_thickness = st.number_input("Skin Thickness", 0)

with col2:
    insulin = st.number_input("Insulin Level", 0)
    bmi = st.number_input("BMI", 0.0, format="%.2f")
    diabetes_pedigree = st.number_input("Diabetes Pedigree Function", 0.0, format="%.3f")
    age = st.number_input("Age", 0, step=1)


# Predict Button
if st.button("🔍 Predict Diabetes"):
    input_data = np.asarray([
        glucose, blood_pressure,
        skin_thickness, insulin, bmi,
        diabetes_pedigree, age
    ]).reshape(1, -1)

    std_data = scaler.transform(input_data)

    prediction = classifier.predict(std_data)[0]
    probability = classifier.predict_proba(std_data)[0][1]

    
    # Prediction Result Display
    if prediction == 0:
        st.success("✅ The person is **NOT diabetic**")
    else:
        st.error("⚠️ The person **IS diabetic**")

    # Probability Gauge (Animated)
    gauge = go.Figure(go.Indicator(
        mode="gauge+number",
        value=probability * 100,
        title={'text': "Diabetes Risk Probability (%)"},
        gauge={
            'axis': {'range': [0, 100]},
            'bar': {'color': "#ef4444"},
            'steps': [
                {'range': [0, 40], 'color': "#22c55e"},
                {'range': [40, 70], 'color': "#eab308"},
                {'range': [70, 100], 'color': "#ef4444"}
            ]
        }
    ))

    st.plotly_chart(gauge, use_container_width=True)

    # Feature Contribution Visualization (User Input)
    features = [
        "Glucose", "Blood Pressure",
        "Skin Thickness", "Insulin", "BMI",
        "Pedigree", "Age"
    ]

    fig = px.bar(
        x=features,
        y=input_data.flatten(),
        title="📊 User Health Feature Profile",
        color=input_data.flatten(),
        color_continuous_scale="tealgrn",
        animation_frame=None
    )

    fig.update_layout(
        template="plotly_dark",
        xaxis_title="Features",
        yaxis_title="Values"
    )

    st.plotly_chart(fig, use_container_width=True)

    # Standardized Feature Radar Chart
    radar = go.Figure()

    radar.add_trace(go.Scatterpolar(
        r=std_data.flatten(),
        theta=features,
        fill='toself',
        name="Standardized Input"
    ))

    radar.update_layout(
        polar=dict(radialaxis=dict(visible=True)),
        showlegend=False,
        title="🧭 Standardized Health Radar"
    )

    st.plotly_chart(radar, use_container_width=True)

    # SHAP EXPLAINABILITY (SAFE)
    st.subheader("🧠 Model Explainability (SHAP)")

    # Create background reference (required)
    background = np.zeros((1, std_data.shape[1]))

    explainer = shap.Explainer(classifier, background, feature_names= ['Glucose', 'Blood Pressure',
        'Skin Thickness', 'Insulin', 'BMI',
        'Diabetes Pedigree Function', 'Age'])
    shap_values = explainer(std_data)

    fig_shap, ax = plt.subplots()
    shap.plots.waterfall(shap_values[0], show=False)
    st.pyplot(fig_shap)

    st.subheader("📄 Medical Report")
    risk_chart_path = create_risk_chart(probability)
    feature_chart_path = create_feature_chart(features, input_data.flatten())
    pdf_path = generate_pdf()

    # Download PDF Report
    with open(pdf_path, "rb") as file:
        st.download_button(
            label="⬇️ Download Medical Report (PDF)",
            data=file,
            file_name="diabetes_medical_report.pdf",
            mime="application/pdf"
        )
