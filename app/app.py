# Create risk probability chart
def create_risk_chart(probability):
    fig, ax = plt.subplots(figsize=(4, 2))
    ax.barh(["Diabetes Risk"], [probability * 100], color="red")
    ax.set_xlim(0, 100)
    ax.set_xlabel("Risk Probability (%)")
    ax.set_title("Diabetes Risk Level")

    temp = tempfile.NamedTemporaryFile(delete=False, suffix=".png")
    plt.tight_layout()
    plt.savefig(temp.name)
    plt.close()
    return temp.name

# Create feature contribution chart
def create_feature_chart(features, values):
    fig, ax = plt.subplots(figsize=(6, 3))
    ax.bar(features, values)
    ax.set_title("User Health Feature Profile")
    ax.set_ylabel("Values")
    ax.tick_params(axis="x", rotation=45)

    temp = tempfile.NamedTemporaryFile(delete=False, suffix=".png")
    plt.tight_layout()
    plt.savefig(temp.name)
    plt.close()
    return temp.name


